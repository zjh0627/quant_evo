def map_to_sw_level_1(industry_code: str) -> str:
    """
    将申万三级行业代码映射到一级行业名称

    Args:
        industry_code: 三级行业代码，如 'J66货币金融服务'

    Returns:
        一级行业名称，如 '银行'
    """
    return SW_INDUSTRY_MAPPING.get(industry_code, '其他')


def get_related_industries(industry: str) -> set:
    """
    获取与指定行业强相关的行业集合

    Args:
        industry: 一级行业名称

    Returns:
        强相关行业集合
    """
    for group in RELATED_INDUSTRY_GROUPS:
        if industry in group:
            return group - {industry}
    return set()


